"""Generate the public engine classes and verified method bindings from metadata."""

import collections
import json
import re

SCALARS = {
    ("Boolean", 1): "bool",
    ("Signed", 1): "int8_t",
    ("Signed", 2): "int16_t",
    ("Signed", 4): "int32_t",
    ("Signed", 8): "int64_t",
    ("Unsigned", 1): "uint8_t",
    ("Unsigned", 2): "uint16_t",
    ("Unsigned", 4): "uint32_t",
    ("Unsigned", 8): "uint64_t",
    ("Float", 4): "float",
    ("Float", 8): "double",
}


def accessor_name(name):
    """Expose PascalCase names while keeping the native spelling in metadata."""
    name = name.strip("_")
    if name.startswith("m_"):
        name = name[2:].lstrip("_")
    elif len(name) > 1 and name[0] == "m" and name[1].isupper():
        name = name[1:]
    return name[:1].upper() + name[1:]


def render_engine_types(root, schema):
    rows = {row["name"]: row for row in schema["types"]}
    bindings = json.loads((root / "native/schema/methods.json").read_text())["methods"]
    quote = json.dumps
    payloads = {
        "Boolean": "boolean",
        "Signed": "signedValue",
        "Unsigned": "unsignedValue",
        "Float": "floatValue",
        "Pointer": "pointer",
        "String": "string",
    }
    for binding in bindings:
        candidates = [
            method
            for method in rows[binding["owner"]].get("methods", [])
            if method["name"] == binding["name"]
            and len(method["arguments"]) == len(binding["parameters"])
        ]
        if len(candidates) != 1:
            raise ValueError(f'A binding must identify one declared method: {binding["symbol"]}')
    names = {}
    used = set()
    for name, row in rows.items():
        if row["kind"] in ("Pointer", "Array") or (
            (row["kind"], row["size"]) in SCALARS and "enum_values" not in row
        ):
            continue
        if "anonymous" in name or "(" in name or not name.strip("<>"):
            result = f'Anonymous_{row["id"]:08x}'
        else:
            result = name.removeprefix("moho::").replace("::", "_").replace("*", "Ptr")
            result = re.sub(r"[^A-Za-z0-9_]", "_", result).strip("_")
            result = re.sub(r"_+", "_", result)
        if (
            not result
            or result[0].isdigit()
            or result in {"void", "class", "const", "Array", "Pointer"}
        ):
            result = "Native_" + result
        if result in used:
            result += f'_{row["id"]:08x}'
        used.add(result)
        names[name] = result

    def cpp(name):
        row = rows[name]
        if name in names:
            return "::FireDragon::FAF::" + names[name]
        if row["kind"] == "Pointer":
            return f'::FireDragon::FAF::Pointer<{cpp(row["element"])}>'
        if row["kind"] == "Array":
            return f'::FireDragon::FAF::Array<{cpp(row["element"])}>'
        return SCALARS[(row["kind"], row["size"])]

    def owners(row):
        return {row["name"], *(base["type"] for base in row.get("bases", []))}

    def callable_methods(row):
        # Native overrides hide base methods with the same name.
        result = {}
        for binding in bindings:
            if binding["owner"] in owners(row):
                if binding["name"] not in result or binding["owner"] == row["name"]:
                    result[binding["name"]] = binding
        return list(result.values())

    def result_type(binding):
        result = binding["result"]
        if result["kind"] == "Reference":
            return cpp(result["element"])
        if result["kind"] == "Pointer":
            return f'::FireDragon::FAF::Pointer<{cpp(result["element"])}>'
        return result["cpp"]

    output = [
        "// Generated by scripts/render_engine_types.py. Do not hand-edit engine classes.",
        "#pragma once",
        '#include "FireDragonEngineSupport.hpp"',
        "namespace FireDragon::FAF {",
    ]
    definitions = []
    for name, typename in names.items():
        row = rows[name]
        if "enum_values" in row:
            scalar = SCALARS[(row["kind"], row["size"])]
            output.append(f"enum class {typename} : {scalar} {{")
            output.extend(f'    {item["name"]} = {item["value"]},' for item in row["enum_values"])
            output.append("};")
        else:
            output.append(f"class {typename};")
    for name, typename in names.items():
        row = rows[name]
        if "enum_values" in row:
            continue
        storage = f'::FireDragon::FAF::Native::View<{row["id"]}>'
        base = f"::FireDragon::FAF::Detail::Record<{storage}>"
        output += [
            f"class {typename} : public {base} {{",
            "  public:",
            f'    static constexpr uint32_t SchemaId = {row["id"]};',
            f"    {typename}() = default;",
            f"    using {base}::Record;",
        ]

        def member(return_type, method, expression):
            expression = re.sub(r"(?<![\w.])native_", base + "::native_", expression)
            expression = re.sub(r"(?<![\w.])engine_", base + "::engine_", expression)
            output.append(f"    {return_type} {method} const;")
            definitions.extend(
                [
                    f"inline {return_type} {typename}::{method} const {{",
                    f"    return {expression};",
                    "}",
                ]
            )

        counts = collections.Counter(field["name"] for field in row["fields"])
        reserved = {
            typename,
            "SchemaId",
            "Address",
            "Inspect",
            "MethodCount",
            "MethodInfo",
            "Invoke",
        }
        reserved.update(binding["name"] for binding in callable_methods(row))
        reserved.update("As" + names[base["type"]] for base in row.get("bases", []))
        if row["kind"] == "String":
            reserved.add("Text")
        if row["element"]:
            reserved.update({"Get", "TryGet"} if row["kind"] == "Shared" else {"Count", "At"})
        for field in row["fields"]:
            field_name = field["name"]
            if counts[field_name] != 1 or not re.fullmatch(r"[A-Za-z_]\w*", field_name):
                continue
            field_type = cpp(field["type"])
            expression = (
                f"::FireDragon::FAF::Detail::Value<{field_type}>(engine_, native_.{field_name}())"
            )
            if field["width"]:
                expression = f"static_cast<{field_type}>(native_.{field_name}().Bits())"
            accessor = accessor_name(field_name)
            if not accessor:
                continue
            if accessor in reserved:
                accessor += "Field"
            # Keep collisions explicit and deterministic; never lose a native
            # field just because its normalized name matches another member.
            while accessor in reserved:
                accessor += "Field"
            reserved.add(accessor)
            member(field_type, accessor + "()", expression)

        base_counts = collections.Counter(base["type"] for base in row.get("bases", []))
        for base_type, count in base_counts.items():
            if count != 1:
                continue
            target = "::FireDragon::FAF::" + names[base_type]
            member(
                target,
                f"As{names[base_type]}()",
                f"{target}(engine_, ::FireDragon::FAF::Native::Object(engine_ ? engine_->fields : nullptr, "
                f'engine_ ? engine_->fields->cast(native_.Reference(), {rows[base_type]["id"]}) : FDObjectRef{{}}))',
            )
        if row["kind"] == "String":
            member("std::string", "Text()", "native_.Text()")
        if row["element"]:
            target = cpp(row["element"])
            if row["kind"] == "Shared":
                member(
                    target,
                    "Get()",
                    f"::FireDragon::FAF::Detail::Value<{target}>(engine_, native_.Dereference())",
                )
                member(target, "operator*()", "Get()")
                member(
                    f"::std::optional<{target}>",
                    "TryGet()",
                    f"::FireDragon::FAF::Detail::TryValue<{target}>(engine_, native_.Dereference())",
                )
            else:
                member("uint32_t", "Count()", "native_.Count()")
                member(
                    target,
                    "At(uint32_t index)",
                    f"::FireDragon::FAF::Detail::Value<{target}>(engine_, native_.At(index))",
                )
        for binding in callable_methods(row):
            result = binding["result"]
            parameters = binding["parameters"]
            declaration = ", ".join(p["cpp"] + " " + p["name"] for p in parameters)
            signature = f'{binding["name"]}({declaration})'
            returns = result_type(binding)
            output.append(f"    {returns} {signature} const;")
            definitions.append(f"inline {returns} {typename}::{signature} const {{")
            if parameters:
                definitions.append(f"    FDMethodValue arguments[{len(parameters)}]{{}};")
                for index, parameter in enumerate(parameters):
                    definitions += [
                        f'    arguments[{index}].kind = FD_METHOD_{parameter["kind"].upper()};',
                        f'    arguments[{index}].value.{payloads[parameter["kind"]]} = {parameter["name"]};',
                    ]
            arguments = "arguments" if parameters else "nullptr"
            definitions.append(
                f'    auto result = Invoke({quote(binding["symbol"])}, {arguments}, {len(parameters)});'
            )
            if result["kind"] == "Boolean":
                expression = "result.value.boolean != 0"
            elif result["kind"] in ("Signed", "Unsigned", "Float", "String"):
                expression = f'static_cast<{returns}>(result.value.{payloads[result["kind"]]})'
            else:
                identifier = rows[result["element"]]["id"]
                if result["kind"] == "Reference":
                    expression = f"{returns}(engine_, result.value.pointer)"
                else:
                    expression = f"{returns}(engine_, result.value.pointer, {identifier})"
            definitions.extend([f"    return {expression};", "}"])
        output.append("};")
    output += definitions
    for alias, identifier in schema["root_types"].items():
        source = next(row for row in rows.values() if row["id"] == identifier)
        if alias != names[source["name"]]:
            assert alias not in used, alias
            output.append(f'using {alias} = {cpp(source["name"])};')
    output.append("} // namespace FireDragon::FAF")
    header = root / "native/include/FireDragonEngine.hpp"
    header.write_text("\n".join(output) + "\n", newline="\n")

    # Introspection covers native signatures even when their ABI is not yet a
    # verified callable binding. It never makes arbitrary headers executable.
    metadata = ["// Generated native method metadata and verified bindings."]
    method_rows = []
    for name, row in rows.items():
        all_methods = []
        for owner in [name, *dict.fromkeys(base["type"] for base in row.get("bases", []))]:
            for method in rows[owner].get("methods", []):
                params = ", ".join(arg["type"] for arg in method["arguments"])
                signature = method["result"] + " " + method["name"] + "(" + params + ")"
                signature += " const" if method["const"] else ""
                binding = next(
                    (b for b in bindings if b["owner"] == owner and b["name"] == method["name"]),
                    None,
                )
                all_methods.append(
                    [
                        method["name"],
                        owner,
                        signature,
                        method["source"],
                        binding["symbol"] if binding else "",
                        bool(binding),
                    ]
                )
        if not all_methods:
            continue
        metadata.append(f'constexpr FDMethodInfo methods_{row["id"]}[] = {{')
        for method in all_methods:
            metadata.append(
                "    {"
                + ", ".join(quote(v) if isinstance(v, str) else str(int(v)) for v in method)
                + "},"
            )
        metadata.append("};")
        method_rows.append(f'    {{{row["id"]}, methods_{row["id"]}, {len(all_methods)}}},')
    metadata += [
        "constexpr MethodRow methodRows[] = {",
        *method_rows,
        "};",
        "const MethodBinding bindings[] = {",
    ]
    symbols = ["// Generated verified method symbols for the FAF 3841 profile."]
    for binding in bindings:
        owner_id = rows[binding["owner"]]["id"]
        bridge = {
            "entity_category": "invokeEntityCategory",
            "thiscall_pointer": "invokeThiscallPointer",
        }[binding["bridge"]]
        metadata.append(f'    {{{quote(binding["symbol"])}, {owner_id}, {bridge}}},')
        symbols += [
            f'if (!add({quote(binding["symbol"])}, {binding["address"]}, {binding["size"]}, {binding["fnv"]})) {{',
            "    return false;",
            "}",
        ]
    metadata.append("};")
    implementation = root / "native/src/generated/native_methods.inc"
    implementation.write_text("\n".join(metadata) + "\n", newline="\n")
    symbol_file = root / "native/src/generated/native_method_symbols.inc"
    symbol_file.write_text("\n".join(symbols) + "\n", newline="\n")
    return [header, implementation, symbol_file]
