"""Render SDK declarations from checked-in native layout facts (no clang required)."""

import argparse
import collections
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def render(formatter):
    schema = json.loads((ROOT / "native/schema/faf3841.fields.json").read_text())
    types = schema["types"]
    ids = {row["name"]: row["id"] for row in types}
    quote = json.dumps
    data = ["// Generated by scripts/render_native_fields.py; edit the schema, not this file."]
    views = [
        "// Generated native field views. Layouts and provenance: sdk/faf3841.fields.json.",
        "#pragma once",
        '#include "FireDragonFields.hpp"',
        "namespace FireDragon::FAF::Native {",
    ]
    definitions = []
    for row in types:
        identifier = row["id"]
        if row["fields"]:
            data.append(f"constexpr FDFieldInfo fields_{identifier}[] = {{")
        for field in row["fields"]:
            data.append(
                "    {"
                + ", ".join(
                    [
                        quote(field["name"]),
                        str(ids[field["type"]]),
                        str(field["offset"]),
                        str(field["bits"]),
                        str(field["width"]),
                        quote(field["declaring"]),
                        quote(field["source"]),
                    ]
                )
                + "},"
            )
        if row["fields"]:
            data.append("};")
        bases = row.get("bases", [])
        if bases:
            data.append(f"constexpr FDBaseInfo bases_{identifier}[] = {{")
            data.extend(f'    {{{ids[base["type"]]}, {base["offset"]}}},' for base in bases)
            data.append("};")
        views += [
            f"template <> class View<{identifier}> : public Object {{",
            "  public:",
            "    View() = default;",
            f"    View(const FDFieldsApi* api, const void* address) : Object(api, {{address, {identifier}, 0, 0}}) {{}}",
            "    explicit View(Object value) : Object(value) {}",
        ]
        scalar = {
            ("Boolean", 1): "bool",
            ("Signed", 1): "int8_t",
            ("Signed", 2): "int16_t",
            ("Signed", 4): "int32_t",
            ("Signed", 8): "int64_t",
            ("Unsigned", 1): "uint8_t",
            ("Unsigned", 2): "uint16_t",
            ("Unsigned", 4): "uint32_t",
            ("Unsigned", 8): "uint64_t",
            ("Float", 4): "float",
            ("Float", 8): "double",
        }.get((row["kind"], row["size"]))
        if scalar:
            views += [
                "    using Object::Read;",
                f"    {scalar} Read() const {{",
                f"        return Object::Read<{scalar}>();",
                "    }",
            ]
        if row["element"] and row["kind"] in ("Pointer", "Shared"):
            target = ids[row["element"]]
            views.append(f"    View<{target}> Dereference() const;")
            definitions += [
                f"inline View<{target}> View<{identifier}>::Dereference() const {{",
                f"    return View<{target}>(Object::Dereference());",
                "}",
            ]
        if row["element"] and row["kind"] not in ("Pointer", "Shared"):
            target = ids[row["element"]]
            views.append(f"    View<{target}> At(uint32_t index) const;")
            definitions += [
                f"inline View<{target}> View<{identifier}>::At(uint32_t index) const {{",
                f"    return View<{target}>(Object::At(index));",
                "}",
            ]
        counts = collections.Counter(field["name"] for field in row["fields"])
        for index, field in enumerate(row["fields"]):
            name = field["name"]
            if counts[name] != 1 or not re.fullmatch(r"[A-Za-z_]\w*", name):
                continue  # Ambiguous inherited names remain accessible by metadata/declaring type.
            target = ids[field["type"]]
            views.append(f"    View<{target}> {name}() const;")
            definitions += [
                f"inline View<{target}> View<{identifier}>::{name}() const {{",
                f'    return View<{target}>(Field({quote(name)}, {quote(field["declaring"])}));',
                "}",
            ]
        views.append("};")
    data.append("constexpr TypeRow types[] = {")
    for row in types:
        kind = "FD_FIELD_" + re.sub(r"(?<!^)(?=[A-Z])", "_", row["kind"]).upper()
        descriptor = ", ".join(
            [
                str(row["id"]),
                quote(row["name"]),
                kind,
                str(row["size"]),
                str(row["alignment"]),
                str(int(row["complete"])),
                str(ids[row["element"]] if row["element"] else 0),
                str(row["count"]),
                str(len(row["fields"])),
                str(len(row.get("bases", []))),
                quote(row["source"]),
            ]
        )
        fields = f'fields_{row["id"]}' if row["fields"] else "nullptr"
        bases = f'bases_{row["id"]}' if row.get("bases") else "nullptr"
        data.append(f"    {{{{{descriptor}}}, {fields}, {bases}}},")
    data.append("};")
    data.append(
        "constexpr uint32_t sortedTypeRows[] = {"
        + ", ".join(
            str(index) for index in sorted(range(len(types)), key=lambda index: types[index]["id"])
        )
        + "};"
    )
    views += definitions
    views += [
        f"using {alias} = View<{identifier}>;" for alias, identifier in schema["root_types"].items()
    ]
    for row in types:
        parts = row["name"].split("::")
        if len(parts) == 2 and all(re.fullmatch(r"[A-Za-z_]\w*", part) for part in parts):
            views.append(f'namespace {parts[0]} {{ using {parts[1]} = View<{row["id"]}>; }}')
    views.append("} // namespace FireDragon::FAF::Native")
    (ROOT / "native/src/generated/native_fields.inc").write_text(
        "\n".join(data) + "\n", newline="\n"
    )
    (ROOT / "native/include/FireDragonFieldViews.hpp").write_text(
        "\n".join(views) + "\n", newline="\n"
    )
    from render_engine_types import render_engine_types

    generated = render_engine_types(ROOT, schema)
    subprocess.run(
        [
            str(formatter),
            "-i",
            "--style=file:" + str(ROOT / "native/.clang-format"),
            str(ROOT / "native/include/FireDragonFieldViews.hpp"),
            str(ROOT / "native/src/generated/native_fields.inc"),
            *map(str, generated),
        ],
        check=True,
    )
    print(f'Rendered {len(types)} native types and {sum(len(t["fields"]) for t in types)} fields')


if __name__ == "__main__":
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--clang-format", type=Path)
    args = parser.parse_args()
    formatter = args.clang_format or shutil.which("clang-format")
    if not formatter:
        candidate = Path("H:/msys64/clang64/bin/clang-format.exe")
        formatter = candidate if candidate.exists() else None
    if not formatter:
        parser.error("clang-format is required to regenerate SDK declarations")
    render(formatter)
